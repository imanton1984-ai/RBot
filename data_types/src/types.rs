/// Position update event
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PositionUpdate {
    /// Timestamp of the update
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Position side
    pub side: TradeSide,
    /// Position size
    pub size: f64,
    /// Average entry price
    pub entry_price: f64,
    /// Unrealized profit/loss
    pub unrealized_pnl: f64,
    /// Leverage
    pub leverage: u16,
    /// Liquidation price
    pub liquidation_price: Option<f64>,
}

/// Exit decision event
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExitDecision {
    /// Timestamp of the decision
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Reason for exit
    pub reason: String,
    /// Action to take
    pub action: ExitAction,
    /// Signal identifier
    pub signal_id: Uuid,
}

/// Exit action enumeration
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum ExitAction {
    /// Close position immediately
    Close,
    /// Tighten stop loss
    TightenSl,
    /// Trail stop loss
    TrailSl,
    /// Scale out
    ScaleOut,
    /// Extend take profit
    ExtendTp,
}