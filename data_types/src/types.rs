/// Raw signal generated by indicator calculations
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RawSignal {
    /// Timestamp of the signal
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Timeframe
    pub timeframe: crate::timeframe::Timeframe,
    /// Signal score (0.0 to 1.0)
    pub score: f64,
    /// Raw indicator scores
    pub indicator_scores: Vec<f64>,
    /// Signal type
    pub signal_type: SignalType,
}

/// Signal type enumeration
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum SignalType {
    /// Long signal
    Long,
    /// Short signal
    Short,
    /// Neutral signal
    Neutral,
}

/// Final signal with ML scoring
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Signal {
    /// Timestamp of the signal
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Timeframe
    pub timeframe: crate::timeframe::Timeframe,
    /// Final score (0.0 to 1.0)
    pub final_score: f64,
    /// ML score
    pub ml_score: f64,
    /// Heuristic score
    pub heur_score: f64,
    /// Reason for the signal
    pub reason: String,
    /// Model version
    pub model_version: String,
    /// Signal identifier for idempotency
    pub signal_id: Uuid,
}

/// Trade intent generated by the scoring system
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TradeIntent {
    /// Timestamp of the intent
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Timeframe
    pub timeframe: crate::timeframe::Timeframe,
    /// Trade direction
    pub side: TradeSide,
    /// Quantity to trade
    pub quantity: f64,
    /// Stop loss price
    pub stop_loss: Option<f64>,
    /// Take profit prices
    pub take_profit: Option<Vec<f64>>,
    /// Final score
    pub score: f64,
    /// Features hash
    pub features_hash: Uuid,
    /// Signal identifier
    pub signal_id: Uuid,
}

/// Trade side enumeration
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum TradeSide {
    /// Buy/Long
    Buy,
    /// Sell/Short
    Sell,
}

/// Order event
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OrderEvent {
    /// Timestamp of the event
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Order ID
    pub order_id: String,
    /// Order type
    pub order_type: OrderType,
    /// Order side
    pub side: TradeSide,
    /// Quantity
    pub quantity: f64,
    /// Price
    pub price: Option<f64>,
    /// Status
    pub status: OrderStatus,
    /// Event type
    pub event_type: OrderEventType,
}

/// Order type enumeration
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
pub enum OrderType {
    /// Market order
    Market,
    /// Limit order
    Limit,
    /// Stop market order
    StopMarket,
    /// Take profit market order
    TakeProfitMarket,
}

/// Order status enumeration
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq)]
