//! Core data types for the trading bot

use serde::{Deserialize, Serialize};
use chrono::{DateTime, Utc};
use uuid::Uuid;

/// A candlestick (OHLCV) data structure
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Candle {
    /// Timestamp of the candle
    pub time: DateTime<Utc>,
    /// Symbol identifier
    pub symbol: String,
    /// Timeframe (1m, 5m, 15m, 1h, 4h, 1d)
    pub timeframe: crate::timeframe::Timeframe,
    /// Opening price
    pub open: f64,
    /// Highest price
    pub high: f64,
    /// Lowest price
    pub low: f64,
    /// Closing price
    pub close: f64,
    /// Trading volume
    pub volume: f64,
    /// Whether this is the final candle for this period
    pub is_final: bool,
}

